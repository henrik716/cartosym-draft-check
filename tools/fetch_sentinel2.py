"""Fetch a Sentinel-2 L2A scene over Rondane and store it in the package.

Usage: uv run --with rasterio --with numpy python tools/fetch_sentinel2.py

Reads one scene of Element84's Earth Search `sentinel-2-c1-l2a` collection
(cloud-optimised GeoTIFFs on AWS, UTM zone 32) over the same 45 x 30 km box as
the Rondane DEM (tools/fetch_rondane.py), reprojects it to EPSG:25833 at 150 m
cells, and writes src/cartosym_draft/sentinel2_data.py: each band as
zlib-compressed little-endian int16, base64 encoded, so the browser playground
can load it as an ordinary module.

- B02, B03, B04, B08 (10 m) are averaged. Since processing baseline 04.00 the
  L2A digital numbers carry a +1000 offset (the item's `offset: -0.1` at
  `scale: 0.0001`); it is removed here, so the stored values are reflectance x
  10 000, as examples 6 and 7 assume.
- SCL (20 m, scene classification) takes the most common class of each cell.

Contains modified Copernicus Sentinel data 2024.
"""

from __future__ import annotations

import base64
import json
import sys
import urllib.request
import zlib
from pathlib import Path

import numpy as np
import rasterio
from rasterio.enums import Resampling
from rasterio.transform import from_origin
from rasterio.vrt import WarpedVRT

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "cartosym_draft" / "sentinel2_data.py"

ITEM = "S2B_T32VNP_20240802T104620_L2A"  # 2 August 2024: no snow, a few compact clouds over the massif
STAC = "https://earth-search.aws.element84.com/v1/collections/sentinel-2-c1-l2a/items/"
X0, Y0 = 205000.0, 6860500.0  # south-west corner in EPSG:25833, as the Rondane DEM
COLS, ROWS, CELL = 300, 200, 150.0
BANDS = {"B02": "blue", "B03": "green", "B04": "red", "B08": "nir"}


def _read(href: str, resampling: Resampling) -> np.ndarray:
    transform = from_origin(X0, Y0 + ROWS * CELL, CELL, CELL)
    with rasterio.Env(GDAL_DISABLE_READDIR_ON_OPEN="EMPTY_DIR", AWS_NO_SIGN_REQUEST="YES"):
        with rasterio.open(href) as src, WarpedVRT(src, crs="EPSG:25833", transform=transform, width=COLS,
                                                   height=ROWS, resampling=resampling) as vrt:
            return vrt.read(1).astype(np.float64)


def _encode(a: np.ndarray) -> list[str]:
    blob = base64.b64encode(zlib.compress(a.astype("<i2").tobytes(), 9)).decode()
    return [blob[i:i + 100] for i in range(0, len(blob), 100)]


def main() -> int:
    item = json.load(urllib.request.urlopen(STAC + ITEM, timeout=60))
    out: dict[str, np.ndarray] = {}
    for band, key in BANDS.items():
        rb = item["assets"][key]["raster:bands"][0]
        if (rb.get("scale"), rb.get("offset")) != (0.0001, -0.1):
            print(f"{band}: unexpected scale/offset {rb}", file=sys.stderr)
            return 1
        dn = _read(item["assets"][key]["href"], Resampling.average)
        if (dn == 0).any():
            print(f"{band}: the box has no-data cells", file=sys.stderr)
            return 1
        out[band] = np.clip(np.round(dn - 1000), 0, 32767)
    out["SCL"] = _read(item["assets"]["scl"]["href"], Resampling.mode)
    if (out["SCL"] == 0).any() or ((out["B08"] + out["B04"]) == 0).any():
        print("the box has no-data cells, or a zero B08 + B04", file=sys.stderr)
        return 1
    lines = [
        '"""Sentinel-2 L2A over Rondane, generated by tools/fetch_sentinel2.py; do not edit.\n',
        f"Scene {ITEM} (Earth Search sentinel-2-c1-l2a), reprojected to EPSG:25833 at 150 m cells;",
        "B02, B03, B04 and B08 as reflectance x 10 000 (the +1000 offset removed), SCL as the scene classification.",
        'Contains modified Copernicus Sentinel data 2024.\n"""\n',
        f'ITEM = "{ITEM}"',
        f"ORIGIN = ({X0}, {Y0})  # south-west corner in EPSG:25833",
        f"COLS, ROWS, CELL = {COLS}, {ROWS}, {CELL}",
        "# Each band row by row from the north edge: little-endian int16, zlib, base64.",
        "BANDS = {",
    ]
    for band, a in out.items():
        lines.append(f'    "{band}": (')
        lines += [f'        "{s}"' for s in _encode(a)]
        lines.append("    ),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    scl = out["SCL"]
    print(f"{OUT}: {OUT.stat().st_size // 1024} KiB; B04 {out['B04'].min():.0f}-{out['B04'].max():.0f}, "
          f"cloud (SCL 8, 9) {100 * np.isin(scl, (8, 9)).mean():.1f} %")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
