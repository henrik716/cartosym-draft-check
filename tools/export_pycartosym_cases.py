"""Export the expression cases for pycartosym's test suite.

Usage: python tools/export_pycartosym_cases.py [path to pycartosym]

Writes tests/data/cartosym_draft_cases.json in pycartosym: for each case, the
CQL2-Text, the expected CQL2-JSON where the case has one, and why the case is
disputed where it is. The `expect` values (what the draft says the result is)
are left out: pycartosym converts expressions, it does not evaluate them.
Run it again after the cases change, and open a pull request to pycartosym.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REPOSITORY = "https://github.com/henrik716/cartosym-draft-check"


def main(argv: list[str]) -> int:
    out = Path(argv[0] if argv else ROOT.parent / "pycartosym") / "tests" / "data" / "cartosym_draft_cases.json"
    git = ["git", "-C", str(ROOT)]
    commit = subprocess.run([*git, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = bool(subprocess.run([*git, "status", "--porcelain", "--", "cases"], capture_output=True, text=True).stdout.strip())
    cases = []
    for f in sorted((ROOT / "cases").glob("*.yaml")):
        for case in yaml.safe_load(f.read_text(encoding="utf-8")):
            if case["kind"] != "expression":
                continue
            entry = {"id": case["id"], "requirement": case["requirement"], "text": case["input"]}
            if "json" in case:
                entry["json"] = case["json"]
            if "disputed" in case:
                entry["disputed"] = case["disputed"]
            cases.append(entry)
    data = {
        "description": "CQL2-Text and CQL2-JSON test cases for the draft requirements of OGC Cartographic Symbology 2.0 "
                       "(opengeospatial/cartographic-symbology#133), from cartosym-draft-check. Generated by "
                       "tools/export_pycartosym_cases.py there; change the cases in that repository, not here.",
        "source": f"{REPOSITORY}/tree/{commit}/cases",
        "license": "MIT, Copyright (c) 2026 Henrik Gulliksen Schüller",
        "cases": cases,
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    # One case per line, so that a change to the cases is a readable diff.
    head = json.dumps({**data, "cases": []}, indent=2, ensure_ascii=False).rsplit("[]", 1)[0]
    body = ",\n".join("    " + json.dumps(c, ensure_ascii=False) for c in cases)
    out.write_text(f"{head}[\n{body}\n  ]\n}}\n", encoding="utf-8")
    with_json = sum("json" in c for c in cases)
    print(f"{len(cases)} cases ({with_json} with CQL2-JSON) from {commit}"
          f"{' (with uncommitted changes)' if dirty else ''} -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
