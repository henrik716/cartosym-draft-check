"""Fetch the Rondane elevation grid from Kartverket and store it in the package.

Usage: uv run --with tifffile --with numpy python tools/fetch_rondane.py

Requests Kartverket's national terrain model (NHM DTM, EPSG:25833) for a
15 x 10 km box over Rondane from the Geonorge WCS at 10 m cells, averages each
10 x 10 block into one 100 m cell, and writes src/cartosym_draft/rondane_data.py:
the elevations in decimetres as zlib-compressed little-endian int16, base64
encoded, so the browser playground can load it as an ordinary module.

Elevation data © Kartverket, CC BY 4.0.
"""

from __future__ import annotations

import base64
import io
import struct
import sys
import urllib.request
import zlib
from pathlib import Path

import numpy as np
import tifffile

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "cartosym_draft" / "rondane_data.py"

WCS = "https://wcs.geonorge.no/skwms1/wcs.hoyde-dtm-nhm-25833"
COVERAGE = "nhm_dtm_topo_25833"
X0, Y0 = 220000.0, 6870500.0  # south-west corner in EPSG:25833
COLS, ROWS, CELL = 150, 100, 100.0  # 15 x 10 km, 100 m cells
FINE = 10  # fetched cells per output cell, in each direction


def main() -> int:
    x1, y1 = X0 + COLS * CELL, Y0 + ROWS * CELL
    url = (f"{WCS}?service=WCS&version=1.0.0&request=GetCoverage&coverage={COVERAGE}&crs=EPSG:25833"
           f"&bbox={X0:.0f},{Y0:.0f},{x1:.0f},{y1:.0f}&width={COLS * FINE}&height={ROWS * FINE}&format=GeoTIFF")
    with urllib.request.urlopen(url, timeout=300) as r:
        if r.headers.get_content_type() != "image/tiff":
            print(r.read(500).decode("utf-8", "replace"), file=sys.stderr)
            return 1
        data = r.read()
    fine = tifffile.imread(io.BytesIO(data)).astype(np.float64)
    if fine.shape != (ROWS * FINE, COLS * FINE):
        print(f"unexpected shape {fine.shape}", file=sys.stderr)
        return 1
    if (fine < -1000).any():
        print("the grid has no-data cells", file=sys.stderr)
        return 1
    grid = fine.reshape(ROWS, FINE, COLS, FINE).mean(axis=(1, 3))  # row 0 is the north edge
    dm = np.round(grid * 10).astype("<i2")
    blob = base64.b64encode(zlib.compress(dm.tobytes(), 9)).decode()
    lines = [blob[i:i + 100] for i in range(0, len(blob), 100)]
    OUT.write_text(
        '"""Rondane elevation, generated by tools/fetch_rondane.py; do not edit.\n\n'
        "Kartverket NHM DTM (EPSG:25833), averaged to 100 m cells. Elevation data © Kartverket, CC BY 4.0.\n"
        '"""\n\n'
        f"ORIGIN = ({X0}, {Y0})  # south-west corner in EPSG:25833\n"
        f"COLS, ROWS, CELL = {COLS}, {ROWS}, {CELL}\n"
        "# Elevations in decimetres, row 0 at the north edge: little-endian int16, zlib, base64.\n"
        "DATA = (\n" + "".join(f'    "{line}"\n' for line in lines) + ")\n",
        encoding="utf-8")
    print(f"{OUT}: {grid.min():.0f} to {grid.max():.0f} m, {len(blob) // 1024} KiB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
